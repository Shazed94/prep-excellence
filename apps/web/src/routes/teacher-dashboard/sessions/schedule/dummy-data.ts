const formatDate = (d: Date) => {
	const y = d.getFullYear();
	const m = String(d.getMonth() + 1).padStart(2, "0");
	const day_ = String(d.getDate()).padStart(2, "0");
	return `${y}-${m}-${day_}`;
};

